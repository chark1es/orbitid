import { z } from "zod";

/** Per-attribute sign-up/sign-in configuration (the "User & Authentication" settings). */
export const attributeSchema = z.object({
  enabled: z.boolean(),
  required: z.boolean().default(false),
  /** Used as identifier on the sign-in form. */
  usedForFirstFactor: z.boolean().default(false),
  usedForSecondFactor: z.boolean().default(false),
  /** Verification strategies allowed for this attribute. */
  verifications: z.array(z.string()).default([]),
  verifyAtSignUp: z.boolean().default(true),
});
export type AttributeConfig = z.infer<typeof attributeSchema>;

/**
 * Maps a provider's claims (or userinfo JSON) to the fields OrbitID stores. Each value is a dotted path
 * (`sub`, `data.user.id`, …); an empty value means "use the provider's standard claim name". Nested paths are
 * supported for OAuth 2.0 providers that wrap their profile in an envelope.
 */
export const claimMappingSchema = z.object({
  sub: z.string().default(""),
  email: z.string().default(""),
  emailVerified: z.string().default(""),
  name: z.string().default(""),
  firstName: z.string().default(""),
  lastName: z.string().default(""),
  username: z.string().default(""),
  picture: z.string().default(""),
});
export type ClaimMapping = z.infer<typeof claimMappingSchema>;

export const socialProviderSchema = z.object({
  enabled: z.boolean().default(false),
  clientId: z.string().default(""),
  clientSecret: z.string().default(""),
  scopes: z.array(z.string()).default([]),
  /** For custom providers (`custom_<key>`): discovery document, or manual endpoints below. */
  discoveryUrl: z.string().optional(),
  name: z.string().optional(),
  /** Custom providers only: OpenID Connect (default) or plain OAuth 2.0 with a userinfo endpoint. */
  protocol: z.enum(["oidc", "oauth2"]).optional(),
  /** Custom providers without a discovery document. */
  authorizationUrl: z.string().optional(),
  tokenUrl: z.string().optional(),
  userinfoUrl: z.string().optional(),
  jwksUrl: z.string().optional(),
  /** Expected `iss` of an ID token; required for ID-token verification with manual endpoints. */
  issuer: z.string().optional(),
  /** How the token request authenticates: HTTP Basic (default) or client id/secret in the form body. */
  clientAuthMethod: z.enum(["client_secret_basic", "client_secret_post"]).optional(),
  /** Send PKCE (S256) with the authorization request. On by default; some providers reject it. */
  pkce: z.boolean().optional(),
  /** Treat the provider's email as verified even when it sends no `email_verified` claim. */
  trustEmailVerified: z.boolean().optional(),
  /** Custom logo shown on the sign-in button; a URL to an image. */
  logoUrl: z.string().optional(),
  claimMapping: claimMappingSchema.optional(),
  /** Not possible in OSS: an operator must supply their own credentials. */
  authenticatableAtSignIn: z.boolean().default(true),
  /** Apple only: the client secret is a short-lived JWT signed with your .p8 key, generated by the server. */
  appleTeamId: z.string().optional(),
  appleKeyId: z.string().optional(),
  applePrivateKey: z.string().optional(),
});
export type SocialProviderConfig = z.infer<typeof socialProviderSchema>;

