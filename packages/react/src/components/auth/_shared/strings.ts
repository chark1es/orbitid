export type TranslateParams = Record<string, string | number | undefined | null>;

export function interpolate(template: string, params?: TranslateParams): string {
  if (!params) return template;
  return template.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? match : String(value);
  });
}

/** Resolve a key against this dictionary. Returns `undefined` for unknown keys. */
export function fallbackTranslate(key: string, params?: TranslateParams): string | undefined {
  const template = (enUS as Record<string, string>)[key];
  return template === undefined ? undefined : interpolate(template, params);
}

export function isStringKey(key: string): key is StringKey {
  return Object.prototype.hasOwnProperty.call(enUS, key);
}
