/**
 * Stable element keys for `appearance.elements`.
 *
 * Two kinds, applied in this order on one DOM node, so the more specific key wins a conflict:
 *
 * - **Primitive keys** are declared by the `@orbitid/ui` primitives themselves (every `Button`, `Input`, `Card`,
 *   `Table`… inside a prebuilt component). A new component built from those primitives adopts them with no extra
 *   code: `elements.buttonPrimary` restyles every primary button in every component.
 * - **Component keys** name a part of a particular flow (`formButtonPrimary`, `headerTitle`, `socialButtonsIconButton`).
 *   Components attach them with `ep(key, …)` (see `useElementProps`).
 *
 * Every key also becomes a stable class, `orbitid-<key>`, for plain CSS. The registry is the single source for the
 * docs table and for the coverage tests: a key used in a component must be listed here, and a key listed here must be
 * used somewhere.
 */
