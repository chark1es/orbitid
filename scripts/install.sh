#!/bin/sh
# Install or upgrade OrbitID with Docker Compose, from the prebuilt image.
#
#   curl -fsSL https://raw.githubusercontent.com/chark1es/orbitid/main/scripts/install.sh | sh
#
# It creates ./orbitid (or ORBITID_DIR), downloads deploy/docker-compose.yml into it, writes a .env with
# freshly generated secrets the first time, pulls the image and starts the stack. Running it again is safe:
# an existing .env is never touched, and a changed compose file replaces the old one only after saving a
# timestamped .bak copy. Settings, all optional and used only when the .env is first created unless noted:
#
#   ORBITID_DIR=orbitid              install directory (every run; `.` when run inside an existing install)
#   ORBITID_PORT=4000                host port to publish
#   ORBITID_BIND=127.0.0.1           host address to publish on; 0.0.0.0 exposes it on every interface
#   ORBITID_BASE_URL=http://localhost:<port>   public URL; set the https:// address when a proxy fronts it
#   ORBITID_VERSION=latest           image tag: latest, or a release such as 1, 1.2 or 1.2.3
#   ORBITID_REF=main                 git ref the compose file is downloaded from (every run)
#   ORBITID_NO_START=1               write the files but do not pull or start anything (every run)
#
# Everything is inside main(), so a download cut short runs nothing.
set -eu

say() { printf '%s\n' "$*"; }
die() { printf 'orbitid install: error: %s\n' "$*" >&2; exit 1; }

fetch() {
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL --proto-redir '=https' --retry 3 -o "$2" "$1"
  elif command -v wget >/dev/null 2>&1; then
    wget -q -O "$2" "$1"
  else
    die "neither curl nor wget is installed; install one of them and run this again."
  fi
}

# Sets COMPOSE to `plugin` (docker compose) or `standalone` (docker-compose v2), or fails.
detect_compose() {
  if docker compose version >/dev/null 2>&1; then
    COMPOSE=plugin
    return
  fi
  if command -v docker-compose >/dev/null 2>&1; then
    compose_version=$(docker-compose version --short 2>/dev/null || true)
    compose_version=${compose_version#v}
    case $compose_version in
      [2-9].* | [1-9][0-9]*.*)
        COMPOSE=standalone
        return
        ;;
    esac
    die "docker-compose ${compose_version:-of unknown version} is too old; install the Docker Compose v2 plugin (https://docs.docker.com/compose/install/)."
  fi
  die "Docker Compose is not installed; install the Docker Compose v2 plugin (https://docs.docker.com/compose/install/)."
}

# Compose lets shell variables override .env. Clear every variable the compose file reads so that the .env
# alone configures the stack, the same as when the operator runs `docker compose` there later.
compose() {
  (
    unset POSTGRES_PASSWORD ORBITID_ENCRYPTION_KEY ORBITID_SECRET_KEY ORBITID_BASE_URL ORBITID_PORT \
      ORBITID_BIND ORBITID_VERSION ORBITID_TRUST_PROXY ORBITID_DB_MAX_CONNECTIONS \
      ORBITID_DB_ACQUIRE_TIMEOUT_MS ORBITID_RESEND_API_KEY ORBITID_SMTP_URL ORBITID_EMAIL_FROM
    if [ "$COMPOSE" = plugin ]; then docker compose "$@"; else docker-compose "$@"; fi
  )
}

# Prints the value of KEY in ./.env (last assignment wins), without surrounding quotes.
env_value() {
  sed -n "s/^[[:space:]]*$1=//p" .env | tail -n 1 | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'\$/\1/"
}

write_env() {
  postgres_password=$(openssl rand -hex 32) || die "openssl could not generate a password."
  encryption_key=$(openssl rand -base64 32) || die "openssl could not generate an encryption key."
  [ -n "$postgres_password" ] && [ -n "$encryption_key" ] || die "openssl produced an empty secret."
  # noclobber: never overwrite a .env that appeared since the check above.
  (
    umask 077
    set -C
    cat > .env <<EOF
# OrbitID settings for docker-compose.yml. Generated by scripts/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Back up this file. ORBITID_ENCRYPTION_KEY must never change: a different key cannot read the signing keys,
# TOTP secrets and OAuth tokens stored in Postgres. POSTGRES_PASSWORD belongs to the database volume.
# Apply changes with: docker compose up -d
POSTGRES_PASSWORD=$postgres_password
ORBITID_ENCRYPTION_KEY=$encryption_key

# Public URL of this server as browsers and your apps reach it. Behind a TLS proxy, use its https:// address
# and set ORBITID_TRUST_PROXY=1.
ORBITID_BASE_URL=$ORBITID_BASE_URL
ORBITID_PORT=$ORBITID_PORT
# Local only until you have created the owner account (the first visitor of a new instance does). Use a reverse
# proxy on this host, or 0.0.0.0 to publish the port on every interface.
ORBITID_BIND=$ORBITID_BIND
# ORBITID_TRUST_PROXY=0

# Image tag: latest, or a major, minor or exact release (1, 1.2, 1.2.3).
ORBITID_VERSION=$ORBITID_VERSION

# Email delivery; this can also be configured in the dashboard under Email & SMS.
# ORBITID_RESEND_API_KEY=
# ORBITID_SMTP_URL=
# ORBITID_EMAIL_FROM=
EOF
  ) || die "could not create $PWD/.env."
  say "Created .env with new secrets. Back it up: the encryption key cannot be recovered."
}

main() {
  # Run again from inside an install directory, upgrade that one instead of creating ./orbitid in it.
  if [ -z "${ORBITID_DIR:-}" ] && [ -f .env ] && [ -f docker-compose.yml ] \
    && grep -q 'ghcr.io/chark1es/orbitid' docker-compose.yml; then
    ORBITID_DIR=.
  fi
  ORBITID_DIR=${ORBITID_DIR:-orbitid}
  ORBITID_PORT=${ORBITID_PORT:-4000}
  ORBITID_BIND=${ORBITID_BIND:-127.0.0.1}
  ORBITID_VERSION=${ORBITID_VERSION:-latest}
  ORBITID_BASE_URL=${ORBITID_BASE_URL:-http://localhost:$ORBITID_PORT}
  ORBITID_REF=${ORBITID_REF:-main}
  ORBITID_NO_START=${ORBITID_NO_START:-0}
  compose_url=${ORBITID_COMPOSE_URL:-https://raw.githubusercontent.com/chark1es/orbitid/$ORBITID_REF/deploy/docker-compose.yml}

  case $ORBITID_PORT in
    '' | *[!0-9]*) die "ORBITID_PORT must be a port number, got '$ORBITID_PORT'." ;;
  esac
  case $ORBITID_BIND in
    '' | *[!0-9a-fA-F.:]*) die "ORBITID_BIND must be an IP address such as 127.0.0.1 or 0.0.0.0, got '$ORBITID_BIND'." ;;
  esac
  case $ORBITID_VERSION in
    '' | *[!A-Za-z0-9._-]*) die "ORBITID_VERSION must be an image tag such as latest or 1.2.3, got '$ORBITID_VERSION'." ;;
  esac
  case $ORBITID_BASE_URL in
    http://?* | https://?*) ;;
    *) die "ORBITID_BASE_URL must start with http:// or https://, got '$ORBITID_BASE_URL'." ;;
  esac

  command -v docker >/dev/null 2>&1 || die "Docker is not installed; see https://docs.docker.com/engine/install/."
  detect_compose
  if [ "$ORBITID_NO_START" != 1 ]; then
    docker info >/dev/null 2>&1 \
      || die "cannot reach the Docker daemon. Start Docker, or run this as a user in the docker group (or with sudo)."
  fi

  mkdir -p "$ORBITID_DIR" || die "cannot create $ORBITID_DIR."
  cd "$ORBITID_DIR" || die "cannot enter $ORBITID_DIR."
  say "Installing OrbitID in $PWD"

  download=docker-compose.yml.download
  trap 'rm -f "$download"' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM
  fetch "$compose_url" "$download" || die "could not download $compose_url."
  grep -q 'ghcr.io/chark1es/orbitid' "$download" \
    || die "$compose_url is not the OrbitID compose file."
  if [ ! -f docker-compose.yml ]; then
    mv "$download" docker-compose.yml
    say "Downloaded docker-compose.yml."
  elif cmp -s "$download" docker-compose.yml; then
    rm -f "$download"
    say "docker-compose.yml is up to date."
  else
    backup="docker-compose.yml.$(date +%Y%m%d%H%M%S).bak"
    cp docker-compose.yml "$backup"
    mv "$download" docker-compose.yml
    say "Updated docker-compose.yml; the previous file is saved as $backup."
  fi

  if [ -e .env ]; then
    say "Keeping the existing .env."
  else
    command -v openssl >/dev/null 2>&1 || die "openssl is needed to generate secrets; install it and run this again."
    write_env
  fi

  compose config -q || die "docker-compose.yml with this .env is not valid; see the message above."

  url=$(env_value ORBITID_BASE_URL)
  port=$(env_value ORBITID_PORT)
  [ -n "$url" ] || url="http://localhost:${port:-4000}"

  if [ "$ORBITID_NO_START" = 1 ]; then
    say "ORBITID_NO_START=1: files are ready. Start with: cd $PWD && docker compose up -d"
    return
  fi

  say "Pulling images..."
  compose pull || die "could not pull the images; check the network and ORBITID_VERSION in .env."
  say "Starting OrbitID (this waits until it is healthy)..."
  if ! compose up -d --wait; then
    compose logs --tail 50 >&2 || true
    die "OrbitID did not become healthy; the logs are above. Inspect them with: cd $PWD && docker compose logs"
  fi

  say ""
  say "OrbitID is running."
  say "  Dashboard:   $url"
  say "  Open it now and create the owner account; the first visitor of a new instance becomes the owner."
  bind=$(env_value ORBITID_BIND)
  if [ "${bind:-127.0.0.1}" = 127.0.0.1 ]; then
    say "  It listens on this host only. Put a reverse proxy in front, or set ORBITID_BIND=0.0.0.0 in .env"
    say "  and run: cd $PWD && docker compose up -d"
  fi
  say "  Secret key:  cd $PWD && docker compose exec orbitid orbitid keys"
  say "  Upgrade:     run this installer again from $PWD, or: cd $PWD && docker compose pull && docker compose up -d"
}

main "$@"
